// Ephemeral audio reclaim. Ephemeral (unsaved) track audio lives exactly as
// long as its Session: deleting a Session reclaims it —
// `evictSessionEphemeralAudio` removes ONLY the audio of the session's
// Ephemeral, audio-bearing tracks (the rows persist for History / one-tap
// re-Save) and queues the files for deletion. A track whose session is already
// GONE has no History to persist for: the orphan paths
// (`evictOrphanedTracksInTx` at the membership chokepoint, the recurring
// `sweepOrphanedTracks`) reclaim it the moment nothing references it.
// Every reclaim is set-based — one guarded write
// plus the batched audio queueing — so a 200-track session costs the same
// handful of statements as a one-track one.

import { LIVE_QUEUE_ITEM_STATES } from '@liedmotif/shared';
import { and, eq, inArray, isNull, sql, type SQL } from 'drizzle-orm';
import type { Database } from '../client';
import { withTransaction, type Transaction } from '../transactions';
import {
  activitySessions,
  activitySessionQueueItems,
  generationRequests,
  tracks,
  trackAudioAssets,
} from '../schema';
import { queueTracksAudioDeletion } from './deletion-queue-repo';

/** Reason recorded on a queued ephemeral audio-file deletion. */
export const EPHEMERAL_EVICTION_REASON = 'ephemeral_eviction';

/** Reason recorded when an orphaned track (no session, no membership) is reclaimed. */
export const ORPHAN_CLEANUP_REASON = 'orphan_cleanup';

/**
 * The "Ephemeral `ready` track" predicate: a `ready` track carrying NO retention
 * flag (Saved/Favorited/Disliked). Shared by both reclaim paths so they can never
 * drift on what counts as Ephemeral.
 */
function ephemeralTrackConditions(): SQL[] {
  return [
    eq(tracks.status, 'ready'),
    isNull(tracks.savedAt),
    isNull(tracks.favoritedAt),
    isNull(tracks.dislikedAt),
  ];
}

/**
 * There is stored audio to reclaim. A track still streaming from the provider
 * holds no stored file, so a session delete leaves it alone rather than handing
 * it a tombstone that reclaims nothing.
 */
function hasStoredAudio(): SQL {
  return sql`exists (
    select 1
    from ${trackAudioAssets} as stored_asset
    where stored_asset.track_id = ${tracks.id}
      and stored_asset.storage_key is not null
  )`;
}

/** The live queue-item states as a parameterized SQL list (from the shared bucket). */
const liveQueueItemStatesSql = sql.join(
  LIVE_QUEUE_ITEM_STATES.map((state) => sql`${state}`),
  sql`, `,
);

/**
 * A track referenced by a LIVE queue item (`planned`/`generating`/`queued`/
 * `playing`) of an ACTIVE session is about to be (or is being) played — evicting
 * its audio would hand the player a dead track while the slot still counts as
 * buffer fill. Part of the reclaim write's own predicate, so a track queued while
 * the reclaim is being decided is still protected (as a concurrent Save is).
 */
function notHeldByActiveSessionQueue(): SQL {
  return sql`not exists (
    select 1
    from ${activitySessionQueueItems} as held_item
    inner join ${activitySessions} as held_session
      on held_session.id = held_item.activity_session_id
    where held_item.track_id = ${tracks.id}
      and held_session.status = 'active'
      and held_item.state in (${liveQueueItemStatesSql})
  )`;
}

/**
 * Any live queue slot still pointing at a reclaimed track (a stopped session's
 * leftover, given the active-session guard on every reclaim) can no longer
 * play: `→ failed` ("audio lost") so a later Resume regenerates the gap
 * instead of believing the buffer is full — mirrors Dislike's `→ rejected`.
 */
async function failLiveQueueItemsFor(tx: Transaction, trackIds: string[]): Promise<void> {
  await tx
    .update(activitySessionQueueItems)
    .set({ state: 'failed' })
    .where(
      and(
        inArray(activitySessionQueueItems.trackId, trackIds),
        inArray(activitySessionQueueItems.state, [...LIVE_QUEUE_ITEM_STATES]),
      ),
    );
}

/**
 * The track's origin is gone: its generation request no longer points at a
 * still-existing session (deleting the session severed the edge `set null`, or
 * the request never had one).
 */
function hasNoLivingSessionEdge(): SQL {
  return sql`not exists (
    select 1
    from ${generationRequests} as origin_request
    inner join ${activitySessions} as origin_session
      on origin_session.id = origin_request.activity_session_id
    where origin_request.id = ${tracks.generationRequestId}
  )`;
}

/** The track was generated by THIS session — the edge a session delete severs. */
function generatedBySession(sessionId: string): SQL {
  return sql`exists (
    select 1
    from ${generationRequests} as origin_request
    where origin_request.id = ${tracks.generationRequestId}
      and origin_request.activity_session_id = ${sessionId}
  )`;
}

/**
 * Reclaim every track matching `conditions` inside the caller's transaction —
 * the one write shape both reclaim paths share: flip `ready → deleted` (cover
 * pointer cleared with the tombstone — a pointer-bearing tombstone would hold
 * its cover_images row alive forever), transition still-live queue items to
 * `failed`, and snapshot-queue-drop the audio assets. The track ROWS stay.
 *
 * Idempotent and race-safe by construction: the caller's FULL predicate is
 * re-checked by this one guarded write, so a track Saved, Favorited, Disliked or
 * queued by an active session since the caller decided it was a candidate simply
 * is not among the reclaimed ids (a concurrent Save wins; playback wins).
 * Returns the ids actually reclaimed.
 */
async function reclaimTracksInTx(
  tx: Transaction,
  args: { conditions: SQL[]; reason: string; now: Date },
): Promise<string[]> {
  const updated = await tx
    .update(tracks)
    .set({ status: 'deleted', coverImageId: null })
    .where(and(...args.conditions))
    .returning({ id: tracks.id });
  if (updated.length === 0) return [];

  const trackIds = updated.map((track) => track.id);
  await failLiveQueueItemsFor(tx, trackIds);
  await queueTracksAudioDeletion(tx, {
    trackIds,
    reason: args.reason,
    deleteAfter: args.now,
  });
  return trackIds;
}

/**
 * The orphan rule: a track with NO living session
 * edge that ends a membership mutation Ephemeral (unsaved, unfavorited, not
 * disliked) is unreachable from every surface — delete it immediately, audio
 * queued with `orphan_cleanup`. The candidate list spans owners (the recurring
 * sweep is instance-wide), which the batched queueing attributes per track.
 */
export async function evictOrphanedTracksInTx(
  tx: Transaction,
  args: { trackIds: string[]; now?: Date },
): Promise<{ evictedTrackIds: string[] }> {
  if (args.trackIds.length === 0) return { evictedTrackIds: [] };
  const evictedTrackIds = await reclaimTracksInTx(tx, {
    conditions: [
      inArray(tracks.id, args.trackIds),
      ...ephemeralTrackConditions(),
      notHeldByActiveSessionQueue(),
      hasNoLivingSessionEdge(),
    ],
    reason: ORPHAN_CLEANUP_REASON,
    now: args.now ?? new Date(),
  });
  return { evictedTrackIds };
}

/**
 * The orphan-track half of the recurring `sweep-orphans` safety net: reclaim
 * tracks the membership chokepoint should have caught (drift, crashes) plus
 * the pre-rule backlog — cross-owner, batched, idempotent. Same guarded write as
 * the chokepoint path.
 */
export async function sweepOrphanedTracks(
  db: Database,
  args: { limit: number; now?: Date },
): Promise<{ evictedTrackIds: string[] }> {
  const now = args.now ?? new Date();
  return withTransaction(db, async (tx) => {
    const candidates = await tx
      .select({ trackId: tracks.id })
      .from(tracks)
      .where(and(...ephemeralTrackConditions(), hasNoLivingSessionEdge()))
      .limit(args.limit);
    return evictOrphanedTracksInTx(tx, {
      trackIds: candidates.map((candidate) => candidate.trackId),
      now,
    });
  });
}

/**
 * Reclaim the audio of EVERY Ephemeral track a session generated, inside the
 * caller's transaction — the session-deletion sweep. Scoped through
 * `generation_requests.activity_session_id`, because deleting the session severs
 * that edge (`set null`) and the tracks' audio would otherwise be orphaned.
 * Durable (Saved/Favorited) tracks are untouched (they live in the Library
 * independent of any session) and Disliked tracks are skipped (their audio was
 * already queued by the Reject purge); a track held live by an ACTIVE session's
 * queue survives because playback wins.
 */
export async function evictSessionEphemeralAudio(
  tx: Transaction,
  args: { sessionId: string; ownerUserId: string; now?: Date },
): Promise<{ evictedTrackIds: string[] }> {
  const evictedTrackIds = await reclaimTracksInTx(tx, {
    conditions: [
      eq(tracks.ownerUserId, args.ownerUserId),
      generatedBySession(args.sessionId),
      ...ephemeralTrackConditions(),
      hasStoredAudio(),
      notHeldByActiveSessionQueue(),
    ],
    reason: EPHEMERAL_EVICTION_REASON,
    now: args.now ?? new Date(),
  });
  return { evictedTrackIds };
}
